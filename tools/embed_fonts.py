"""Embed the UI fonts and the app icon (res/icon_256.png) into src/host/embedded_fonts.c.

The fonts (Chakra Petch, SIL OFL 1.1) live in res/fonts. Run this after
changing them: python tools/embed_fonts.py
"""
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
FONTS = [("font_body", "fonts/ChakraPetch-SemiBold.ttf"), ("font_title", "fonts/ChakraPetch-Bold.ttf"),
         ("app_icon_png", "icon_256.png")]


def main():
    out = ['/* Generated by tools/embed_fonts.py from res/fonts (Chakra Petch, SIL OFL 1.1). */',
           '#include <stddef.h>', '']
    for sym, fn in FONTS:
        data = open(os.path.join(ROOT, "res", fn), "rb").read()
        out.append(f"const unsigned char {sym}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"const size_t {sym}_size = {len(data)};")
        out.append("")
    open(os.path.join(ROOT, "src", "host", "embedded_fonts.c"), "w").write("\n".join(out))


if __name__ == "__main__":
    main()
