#!/usr/bin/env python3
"""Embed the Lola Retro passes (third_party/lola-retro, MIT) into src/host/crt_shaders.c.

The passes are the Kodi build of Lola Retro (RetroArch-style GLSL 3.30, one file per pass with
VERTEX and FRAGMENT parts, exact-size textures), all from one preset chain. The Mega Drive
preset's parameter values (systems/flat/mega-drive-genesis.slangp) are embedded too; the
host's CRT presets change a few of them (cable, curvature).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'third_party', 'lola-retro')
OUT = os.path.join(ROOT, 'src', 'host', 'crt_shaders.c')
PASSES = ['native', 'encode', 'decode', 'glow-h', 'glow-v', 'beam', 'crt', 'present']

def c_bytes(data):
    out = []
    for i in range(0, len(data), 24):
        out.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    return '\n'.join(out)

def main():
    lines = ['/* Generated by tools/embed_crt.py from third_party/lola-retro (MIT, see its LICENSE). Do not edit. */',
             '#include "crt_shaders.h"', '']
    for p in PASSES:
        data = open(os.path.join(SRC, p + '.glsl'), 'rb').read() + b'\0'
        name = 'lr_' + p.replace('-', '_')
        lines.append('static const unsigned char %s[] = {\n%s\n};' % (name, c_bytes(data)))
    lines.append('const char *const crt_pass_src[CRT_PASSES] = {')
    for p in PASSES:
        lines.append('    (const char *)lr_%s,' % p.replace('-', '_'))
    lines.append('};')
    # the Mega Drive preset's parameter values
    vals = []
    for line in open(os.path.join(SRC, 'mega-drive-genesis.slangp')):
        m = re.match(r'^(LR_[A-Z0-9_]+)\s*=\s*([-0-9.]+)', line)
        if m:
            vals.append((m.group(1), m.group(2)))
    lines.append('const crt_param crt_md_params[] = {')
    for k, v in vals:
        lines.append('    { "%s", %sf },' % (k, v if '.' in v else v + '.0'))
    lines.append('    { 0, 0 }')
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', OUT, os.path.getsize(OUT), 'bytes,', len(vals), 'parameters')

if __name__ == '__main__':
    main()
